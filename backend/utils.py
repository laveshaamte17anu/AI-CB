import re
import os
import logging

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger("local-ai-assistant")

def clean_thinking_text(text: str) -> str:
    """
    Removes <think>...</think> blocks and internal reasoning monologues
    generated by reasoning models like Qwen 3.
    """
    if not text:
        return ""
    
    # 1. Remove well-formed <think>...</think> blocks
    cleaned = re.sub(r'<think>.*?</think>', '', text, flags=re.DOTALL)
    if '</think>' in cleaned:
        cleaned = cleaned.split('</think>')[-1]
    if '<think>' in cleaned:
        cleaned = cleaned.split('<think>')[0]
        
    cleaned = cleaned.strip()

    # 2. Filter out raw reasoning monologues (e.g. "Okay, the user said...", "Hmm, let me check...")
    paragraphs = [p.strip() for p in cleaned.split('\n\n') if p.strip()]
    if len(paragraphs) > 1:
        non_reasoning = []
        for p in paragraphs:
            # Check if paragraph is internal thinking process
            is_reasoning = re.match(
                r'^(okay|hmm|let me|i need to|the user|earlier,|first,|so,|i should|i will|let\'s|i must|the assistant)',
                p,
                re.IGNORECASE
            )
            if not is_reasoning:
                non_reasoning.append(p)
                
        if non_reasoning:
            cleaned = " ".join(non_reasoning)
        else:
            cleaned = paragraphs[-1] # Pick final answer block

    return cleaned.strip()

def safe_remove_file(file_path: str):
    """
    Safely deletes temporary audio files without raising exceptions.
    """
    if file_path and os.path.exists(file_path):
        try:
            os.remove(file_path)
            logger.info(f"Temporary file removed: {file_path}")
        except Exception as e:
            logger.warning(f"Could not remove temporary file {file_path}: {e}")
